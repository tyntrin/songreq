const dictionaries: Record<Locale, Record<CustomerKey, string>> = { th, en };

export function pickLocale(cookieValue: string | undefined, acceptLanguage: string | null): Locale {
  if (cookieValue === "th" || cookieValue === "en") return cookieValue;
  const first = acceptLanguage?.split(",")[0]?.trim().toLowerCase() ?? "";
  return first.startsWith("en") ? "en" : "th";
}

export function t(
  locale: Locale,
  key: CustomerKey,
  vars?: Record<string, string | number>,
): string {
  const s = dictionaries[locale][key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
